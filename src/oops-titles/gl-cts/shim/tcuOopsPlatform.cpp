/*
 * The platform layer: what dEQP needs to know about this console.
 *
 * `framework/platform/` holds one directory per operating system - X11, Win32, Android, OSX,
 * QNX, Fuchsia - and none of them is this one. This file is the equivalent, and it is
 * deliberately the *only* thing this port writes. Everything else compiled here is upstream's,
 * which is the property that makes a CTS result worth having.
 *
 * # What a platform owes dEQP, and nothing more
 *
 * Four things, and they are all in `gluRenderContext.hpp`:
 *
 *   - `getType()`        what GL version and profile this context is
 *   - `getFunctions()`   the `glw::Functions` table the tests call through
 *   - `getRenderTarget()` the size and format of what is being drawn to
 *   - `postIterate()`    present the frame; called at the end of each test case
 *
 * There is no event loop, no window manager, no surface negotiation. `oops_gl_create` opens the
 * display and makes a context current in one call, which is the whole of what the X11 platform
 * spends four files doing.
 *
 * # Only the GL platform is implemented
 *
 * `tcu::Platform` also offers `getEGLPlatform()` and `getVulkanPlatform()`, and the base class
 * implementations throw `NotSupportedError`. That is the correct answer here and it is left
 * alone: this collection has no EGL (oops-mesa D010 records why the DRI frontend is used
 * instead) and no Vulkan. A suite run asks for the GL platform and never reaches the others.
 */
