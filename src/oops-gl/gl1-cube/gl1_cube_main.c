/*
 * gl1-cube: Clean-room 3D Colored Cube Demo using oops-gl (OpenGL 1.x / GLU)
 *
 * **The pinned hardware oracle**, and named `gl1-` since 2026-09-17 to pair with `gl2-cube`.
 * Its frame is measured on a retail console and asserted register by register by
 * `test_pm4_gl_honours_the_gl_cube_oracle_record` in oops-sdk - so unlike `gl1-probe`, which
 * checks that features produce the right pixels, this checks that the emitted command stream is
 * still the one a console was proven to accept. The title id stays `GLCB00001` because the
 * record names it; see `app.env`.
 * Target: Sony PlayStation 5 (AMD RDNA2 GFX10.3 / Prospero FW 12.40)
 */

